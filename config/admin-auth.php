<?php

declare(strict_types=1);

return [

    /*
    |
    | This option controls which defaults are used for admin users
    |
    */

    'defaults' => [
        'guard' => 'admin',
        'passwords' => 'admin_users',
        'activations' => 'admin_users',
    ],

    /*
    |
    | This option controls if Login should check also forbidden key
    |
    */

    'check_forbidden' => env('FORBIDDEN_ENABLED', false),

    /*
    |
    | This option controls if Login should check also enabled key
    |
    */

    'activation_enabled' => env('ACTIVATION_ENABLED', false),

    /*
    |--------------------------------------------------------------------------
    | Login
    |--------------------------------------------------------------------------
    |
    | This option controls the url for redirect after login
    |
    */

    'login_redirect' => '/admin',

    /*
    |--------------------------------------------------------------------------
    | Logout
    |--------------------------------------------------------------------------
    |
    | This option controls the url for redirect after logout
    |
    */

    'logout_redirect' => '/admin/login',

    /*
    |--------------------------------------------------------------------------
    | Password reset
    |--------------------------------------------------------------------------
    |
    | This option controls the url for redirect after password reset
    |
    */

    'password_reset_redirect' => '/admin/login',

    /*
    |--------------------------------------------------------------------------
    | Activations
    |--------------------------------------------------------------------------
    |
    | This options controls if activation is required or not
    | And the activation redirect controls where to redirect after activation
    |
    */

    'activation_redirect' => '/admin/login',

    /*
    |
    | This option handles the self activation form accessibility.
    |
    */

    'self_activation_form_enabled' => true,

    /*
    |--------------------------------------------------------------------------
    | Routes
    |--------------------------------------------------------------------------
    |
    | This option controls if package routes are used or not
    |
    */

    'use_routes' => true,

    /*
    |--------------------------------------------------------------------------
    | Profile
    |--------------------------------------------------------------------------
    |
    | Controls the "My profile" (/admin/profile) and "Change password"
    | (/admin/password) pages shipped by this package. Both are registered
    | together:
    |   'auto' - only when the application has no route named admin/edit-profile
    |            (a profile generated by admin:generate:admin-user:profile)
    |   true   - always
    |   false  - never
    |
    */

    'profile' => [
        'enabled' => env('ADMIN_AUTH_PROFILE', 'auto'),
    ],

    /*
    |--------------------------------------------------------------------------
    | Two-factor authentication
    |--------------------------------------------------------------------------
    |
    | Every admin can turn on two-factor authentication (TOTP) at
    | /admin/two-factor. These options only decide whether it is required:
    |   required       - when true, admins must enrol before using the admin
    |   required_roles - limits "required" to admins with one of these roles
    |                    (comma-separated in the env); empty = every admin
    |   issuer         - the name shown in the authenticator app; null = app.name
    |
    */

    'two_factor' => [
        'required' => (bool) env('ADMIN_TWO_FACTOR_REQUIRED', false),
        'required_roles' => array_values(array_filter(
            array_map('trim', explode(',', (string) env('ADMIN_TWO_FACTOR_REQUIRED_ROLES', ''))),
            static fn (string $role): bool => $role !== '',
        )),
        'issuer' => null,
    ],

    /*
    |--------------------------------------------------------------------------
    | Passkeys
    |--------------------------------------------------------------------------
    |
    | Every admin can add passkeys (WebAuthn) at /admin/passkeys, to sign in
    | without a password or as the second factor. These options only set the
    | relying party; the defaults come from app.url and app.name:
    |   rp_id           - the domain passkeys are bound to; null = host of app.url.
    |                     Changing it later makes every existing passkey unusable.
    |   rp_name         - the name shown by the browser; null = app.name
    |   allowed_origins - origins the admin is served on (comma-separated in the
    |                     env); empty = scheme, host and port of app.url
    |
    */

    'passkeys' => [
        'rp_id' => env('ADMIN_PASSKEYS_RP_ID'),
        'rp_name' => env('ADMIN_PASSKEYS_RP_NAME'),
        'allowed_origins' => array_values(array_filter(
            array_map('trim', explode(',', (string) env('ADMIN_PASSKEYS_ALLOWED_ORIGINS', ''))),
            static fn (string $origin): bool => $origin !== '',
        )),
    ],
];
